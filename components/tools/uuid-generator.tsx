"use client";

import { useEffect, useState } from "react";
import { CopyButton } from "@/components/ui/CopyButton";

function randomId(): string {
  const source = globalThis.crypto as Crypto & { randomUUID?: () => string };
  if (typeof source.randomUUID === "function") return source.randomUUID();
  const bytes = new Uint8Array(16);
  source.getRandomValues(bytes);
  bytes[6] = (bytes[6]! & 0x0f) | 0x40;
  bytes[8] = (bytes[8]! & 0x3f) | 0x80;
  const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

function build(count: number, uppercase: boolean, braces: boolean, noHyphens: boolean): string[] {
  return Array.from({ length: count }, () => {
    let id = randomId();
    if (noHyphens) id = id.replace(/-/g, "");
    if (uppercase) id = id.toUpperCase();
    if (braces) id = `{${id}}`;
    return id;
  });
}

function download(ids: string[]) {
  const blob = new Blob([`${ids.join("\n")}\n`], { type: "text/plain" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = "uuids.txt";
  link.click();
  URL.revokeObjectURL(url);
}

export default function UuidGenerator() {
  const [ids, setIds] = useState<string[]>([]);
  const [count, setCount] = useState("5");
  const [uppercase, setUppercase] = useState(false);
  const [braces, setBraces] = useState(false);
  const [noHyphens, setNoHyphens] = useState(false);

  useEffect(() => {
    setIds(build(5, false, false, false));
  }, []);

  function generate() {
    const parsed = Math.min(100, Math.max(1, Number.parseInt(count, 10) || 1));
    setCount(String(parsed));
    setIds(build(parsed, uppercase, braces, noHyphens));
  }

  return (
    <div className="tool-panel">
      <div className="row-wrap">
        <div className="field" style={{ width: 120 }}>
          <label htmlFor="uuid-count">How many</label>
          <input
            id="uuid-count"
            className="input"
            type="number"
            min="1"
            max="100"
            value={count}
            onChange={(event) => setCount(event.target.value)}
          />
        </div>
        <div className="field grow">
          <span className="field-label">Format</span>
          <div style={{ display: "flex", gap: 14, flexWrap: "wrap", alignItems: "center", minHeight: 44 }}>
            <label style={{ display: "flex", gap: 6, alignItems: "center", fontSize: 13 }}>
              <input type="checkbox" checked={uppercase} onChange={(event) => setUppercase(event.target.checked)} />
              Uppercase
            </label>
            <label style={{ display: "flex", gap: 6, alignItems: "center", fontSize: 13 }}>
              <input type="checkbox" checked={braces} onChange={(event) => setBraces(event.target.checked)} />
              Braces
            </label>
            <label style={{ display: "flex", gap: 6, alignItems: "center", fontSize: 13 }}>
              <input type="checkbox" checked={noHyphens} onChange={(event) => setNoHyphens(event.target.checked)} />
              No hyphens
            </label>
          </div>
        </div>
        <button type="button" className="btn btn-primary" style={{ height: 44 }} onClick={generate}>
          Generate
        </button>
      </div>

      <p className="micro" style={{ marginTop: 12 }}>
        Version 4, generated by the browser&apos;s cryptographic random source. 122 random bits; no server involved.
      </p>

      <div className="output" style={{ marginTop: 16, display: "flex", flexDirection: "column", gap: 6 }}>
        {ids.length === 0 ? (
          <span className="micro">Generating…</span>
        ) : (
          ids.map((id) => (
            <div key={id} style={{ display: "flex", justifyContent: "space-between", gap: 10, alignItems: "center" }}>
              <span style={{ overflowWrap: "anywhere" }}>{id}</span>
              <CopyButton value={id} label="Copy" copiedLabel="Copied" className="btn btn-sm" />
            </div>
          ))
        )}
      </div>

      <div style={{ display: "flex", gap: 8, marginTop: 14, flexWrap: "wrap" }}>
        <CopyButton value={ids.join("\n")} label={`Copy all (${ids.length})`} />
        <button type="button" className="btn btn-sm" onClick={() => download(ids)} disabled={ids.length === 0}>
          Download .txt
        </button>
      </div>
    </div>
  );
}
